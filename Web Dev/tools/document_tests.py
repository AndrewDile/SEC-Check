"""Regenerate tests/current_tests.md: every test as the HTTP requests it sends and the responses it expects.

    python tools/document_tests.py

Runs the whole test suite, records each HTTP request a test makes (and the Core API
calls the Web App made on its behalf), and writes them out with the test's
assertions. Because the document is produced from a passing run, the recorded
responses are the expected outputs. If any test fails, nothing is written.
"""
from __future__ import annotations

import inspect
import json
import re
import sys
import textwrap
import unittest
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit

WEB_DEV = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(WEB_DEV))
OUT = WEB_DEV / "tests" / "current_tests.md"
MODULES = ["tests.test_incidents", "tests.test_tickets", "tests.test_dependencies_and_misc",
           "tests.test_core_gateway", "tests.test_contracts"]
WEB_APP_PREFIXES = ("/webapp/v1", "/app", "/openapi.json", "/docs")
FIXED_IDS = {"102356304331", "000000000001", "555"}

import tests.helpers as helpers  # noqa: E402

RECORD = {}          # test id -> list of request records
CORE_CALLS = {}      # test id -> list of "path Method" the Web App sent to the Core API
FORWARDS = {}        # test id -> list of Web App requests the Core API generated (gateway mode)
CURRENT = {"id": None}
_real_http = helpers.http


def recording_http(method, url, body=None, headers=None):
    status, data = _real_http(method, url, body, headers)
    if CURRENT["id"]:
        RECORD.setdefault(CURRENT["id"], []).append({
            "method": method, "url": url, "body": body, "headers": dict(headers or {}), "status": status, "data": data,
        })
    return status, data


helpers.http = recording_http  # patch before test modules import it


class RecordingResult(unittest.TextTestResult):
    def startTest(self, test):
        CURRENT["id"] = test.id()
        super().startTest(test)

    def stopTest(self, test):
        stack = getattr(test, "stack", None)
        if stack is not None:
            CORE_CALLS[test.id()] = [f"{e['path']} {e['body'].get('Method') or e['body'].get('method')}"
                                     for e in stack.mock.request_log if e.get("origin") == "webapp"]
            FORWARDS[test.id()] = [e["web"] for e in stack.mock.forward_log]
        CURRENT["id"] = None
        super().stopTest(test)


# ---------------------------------------------------------------- formatting helpers
def shorten(value, limit=110):
    if isinstance(value, str):
        return value if len(value) <= limit else value[:limit] + "…"
    if isinstance(value, list):
        items = [shorten(v, limit) for v in value[:6]]
        return items + [f"… {len(value) - 6} more"] if len(value) > 6 else items
    if isinstance(value, dict):
        return {k: shorten(v, limit) for k, v in value.items()}
    return value


def body_text(record):
    data = record["data"]
    path = urlsplit(record["url"]).path
    if path.endswith(".png"):
        return None, "(PNG image)"
    if isinstance(data, str):
        return None, "(HTML page)" if data.lstrip().lower().startswith("<!doctype") else "(non-JSON body)"
    if isinstance(data, dict) and "openapi" in data and "paths" in data:
        return None, f"(OpenAPI document: \"{data.get('info', {}).get('title')}\")"
    return json.dumps(shorten(data), indent=2), None


def sanitize(text, today):
    text = re.sub(r"http://127\.0\.0\.1:\d+", "<local-url>", text)
    text = re.sub(rf"{today}T\d{{2}}:\d{{2}}:\d{{2}}\.\d{{3}}Z", "<now>", text)
    return text


def label_ids(test_id, records):
    """Map randomly generated incident ids to <incident_id>, <incident_id_2>, … per test."""
    found = []
    for r in records:
        for m in re.findall(r"\b\d{12}\b", json.dumps(r["data"]) + " " + r["url"]):
            if m not in FIXED_IDS and m not in found:
                found.append(m)
    return {fid: ("<incident_id>" if i == 0 else f"<incident_id_{i + 1}>") for i, fid in enumerate(found)}


def assertions(fn):
    lines = inspect.getsource(fn).splitlines()
    picked, cont = [], False
    for line in lines:
        s = line.strip()
        if s.startswith("self.assert") or cont:
            picked.append(s)
            cont = s.count("(") > s.count(")") or s.endswith(",")
    return picked


def humanize(name):
    return name[len("test_"):].replace("_", " ").capitalize() if name.startswith("test_") else name


def render(today, outcome):
    out = [
        "# Current tests",
        "",
        "Generated by `python tools/document_tests.py` from a passing run of the test suite "
        f"({outcome.testsRun} tests, {len(outcome.skipped)} skipped). Regenerate it after changing the tests.",
        "",
        "Each test runs against two real local servers: the Web App and a fresh, empty mock Core API "
        "(see `tests/helpers.py`). For every test this file lists:",
        "",
        "- the HTTP requests the test sends, in order: to the Web App (with the signed-in user, `X-User` header), "
        "or straight to the Core API (marked **Core API**), as the system's API test clients do;",
        "- the response each request returned, which is the expected output because the run passed;",
        "- in gateway tests, the Web App API requests the Core API generated from those Core API calls;",
        "- the Core API calls the Web App made on the test's behalf;",
        "- the test's assertions, copied from the source.",
        "",
        "Every Web App response is checked against the Web App contract; every Core API response, and every Core API "
        "call the Web App makes, against the Core contract.",
        "",
        "Placeholders: `<incident_id>` is a randomly generated 12-digit ID, `<now>` is the time of the request, "
        "`<local-url>` is a localhost address (the mock Core API, or a deliberately unreachable one). All paths start with `/webapp/v1` unless shown otherwise. "
        "Long values are shortened with `…`.",
        "",
    ]
    suite_tests = {}
    for mod_name in MODULES:
        mod = sys.modules[mod_name]
        classes = [c for _, c in inspect.getmembers(mod, inspect.isclass)
                   if issubclass(c, unittest.TestCase) and c.__module__ == mod_name]
        classes.sort(key=lambda c: inspect.getsourcelines(c)[1])
        suite_tests[mod_name] = classes

    out.append("## Contents\n")
    for mod_name, classes in suite_tests.items():
        file = mod_name.split(".")[-1] + ".py"
        out.append(f"- `{file}`: " + ", ".join(f"[{c.__name__}](#{c.__name__.lower()})" for c in classes))
    out.append("")

    for mod_name, classes in suite_tests.items():
        file = mod_name.split(".")[-1] + ".py"
        mod_doc = (sys.modules[mod_name].__doc__ or "").strip().splitlines()[0] if sys.modules[mod_name].__doc__ else ""
        out += [f"## `{file}`", "", mod_doc, ""] if mod_doc else [f"## `{file}`", ""]
        for cls in classes:
            out += [f"### {cls.__name__}", ""]
            extra = getattr(cls, "stack_settings", None)
            if extra:
                out += [f"Runs with settings: `{json.dumps(extra)}`.", ""]
            if "setUp" in cls.__dict__:
                out += ["Each test first runs this setup (its requests are included below):", "",
                        "```python", textwrap.dedent(inspect.getsource(cls.setUp)).strip(), "```", ""]
            methods = [(n, f) for n, f in cls.__dict__.items() if n.startswith("test_") and callable(f)]
            methods.sort(key=lambda m: inspect.getsourcelines(m[1])[1])
            for name, fn in methods:
                tid = f"{mod_name}.{cls.__name__}.{name}"
                doc = (fn.__doc__ or "").strip()
                out += [f"#### {humanize(name)}", "", f"`{name}`" + (f": {doc}" if doc else ""), ""]
                records = RECORD.get(tid, [])
                ids = label_ids(tid, records)
                section = []
                if tid in [t[0].id() for t in outcome.skipped]:
                    reason = next(r for t, r in outcome.skipped if t.id() == tid)
                    section.append(f"*Skipped in this run: {reason}*\n")
                if not records:
                    section.append("No HTTP requests: this test inspects the code and contract files directly.\n")
                for i, r in enumerate(records, 1):
                    parts = urlsplit(r["url"])
                    path = parts.path + (f"?{parts.query}" if parts.query else "")
                    to_core = not parts.path.startswith(WEB_APP_PREFIXES)
                    if path.startswith("/webapp/v1"):
                        path = path[len("/webapp/v1"):] or "/"
                    who = r["headers"].get("X-User")
                    cookie = r["headers"].get("Cookie")
                    if to_core:
                        section.append(f"**{i}.** **Core API** `{r['method']} {path}`\n")
                    else:
                        auth = f" as `{who}`" if who else (f" with cookie `{cookie}`" if cookie else " (not signed in)")
                        section.append(f"**{i}.** `{r['method']} {path}`{auth}\n")
                    if r["body"] is not None:
                        if isinstance(r["body"], bytes):
                            section.append(f"Raw body: `{r['body'].decode(errors='replace')}`\n")
                        else:
                            section.append("```json\n" + json.dumps(shorten(r["body"]), indent=2) + "\n```\n")
                    pretty, note = body_text(r)
                    section.append(f"Expected: **{r['status']}**" + (f" {note}" if note else "") + "\n")
                    if pretty:
                        section.append("```json\n" + pretty + "\n```\n")
                forwards = FORWARDS.get(tid)
                if forwards:
                    section.append("Web App requests generated by the Core API: " + ", ".join(f"`{w}`" for w in forwards) + "\n")
                calls = CORE_CALLS.get(tid)
                if calls:
                    section.append("Core API calls made by the Web App: " + ", ".join(f"`{c}`" for c in calls) + "\n")
                checks = assertions(fn)
                if checks:
                    section.append("Assertions:\n\n```python\n" + "\n".join(checks) + "\n```\n")
                text = "\n".join(section)
                for real, placeholder in ids.items():
                    text = text.replace(real, placeholder)
                out.append(sanitize(text, today))
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    loader = unittest.TestLoader()
    suite = unittest.TestSuite(loader.loadTestsFromName(m) for m in MODULES)
    runner = unittest.TextTestRunner(resultclass=RecordingResult, verbosity=0, stream=open(__import__("os").devnull, "w"))
    outcome = runner.run(suite)
    if not outcome.wasSuccessful():
        print(f"Tests failed ({len(outcome.failures)} failures, {len(outcome.errors)} errors); not writing {OUT.name}.")
        for test, trace in outcome.failures + outcome.errors:
            print(f"\n{test.id()}\n{trace}")
        return 1
    OUT.write_text(render(today, outcome), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(WEB_DEV)} ({outcome.testsRun} tests, {sum(len(v) for v in RECORD.values())} requests).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
